"""Pack the Yale Bright Star Catalogue (5th ed., CDS V/50) into a Swift source file.

    curl -sO https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz && gunzip catalog.gz
    python3 -I docs/catalog/build_bsc5.py catalog > Sources/SkyKit/StarCatalog+BSC5.swift

Seven bytes a star, little-endian: RA as uint16 of a full turn, Dec as int16 of a half
turn, V as int16 hundredths, B-V as int8 fiftieths (127 = unknown). 9096 stars with a
J2000 position and a V magnitude; the 14 novae and non-stellar entries without one drop.
"""
import base64
import struct
import sys
import textwrap

rows = []
for line in open(sys.argv[1], encoding="latin-1"):
    line = line.rstrip("\n").ljust(115)
    ra_h, ra_m, ra_s = line[75:77], line[77:79], line[79:83]
    de_sign, de_d, de_m, de_s = line[83], line[84:86], line[86:88], line[88:90]
    vmag, bv = line[102:107], line[109:114]
    if not ra_h.strip() or not vmag.strip():
        continue
    ra = (int(ra_h) + int(ra_m) / 60 + float(ra_s) / 3600) * 15
    dec = int(de_d) + int(de_m) / 60 + int(de_s) / 3600
    if de_sign == "-":
        dec = -dec
    color = round(float(bv) * 50) if bv.strip() else 127
    rows.append(struct.pack(
        "<Hhhb",
        round(ra / 360 * 65536) % 65536,
        round(dec / 90 * 32767),
        round(float(vmag) * 100),
        max(-127, min(126, color)),
    ))

payload = base64.b64encode(b"".join(rows)).decode()
body = "\n".join(textwrap.wrap(payload, 100))
print(f"""// Generated by docs/catalog/build_bsc5.py from the Yale Bright Star Catalogue, 5th revised
// edition (Hoffleit & Warren 1991, CDS V/50). Do not edit by hand.
// swiftlint:disable file_length

extension StarCatalog {{
    static let starCount = {len(rows)}
    static let packed = \"\"\"
{body}
\"\"\"
}}""")
